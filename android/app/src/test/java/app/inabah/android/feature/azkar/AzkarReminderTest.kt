package app.inabah.android.feature.azkar

import kotlin.test.assertEquals
import org.junit.Test

/**
 * «Сделать напоминание» — новый вид (решение пользователя 2026-10-11, `docs/02-screen-azkar.md`, «Новый вид»):
 * «⚠️» в заголовке, разделители из 30 «•», слова Абу ад-Дарды отдельным абзацем, «✅» перед временем, ссылка.
 */
class AzkarReminderTest {
    private val separator = "••••••••••••••••••••••••••••••"

    @Test
    fun `Напоминание — текст целиком, как в iOS`() {
        val text = azkarReminderText(
            title = "⚠️ Утренние азкары ⚠️",
            call = "О рабы Аллаха, защитите себя и свою семью от сглаза, зависти и колдовства: прочитайте утренние азкары.",
            quoteIntro = "Абу ад-Дарда сказал:",
            quoteTranslation = "«Те, чьи языки влажные от поминания Аллаха, войдут в Рай смеясь».",
            quoteSource = "Ахмад в «аз-Зухд», 726",
            bestTime = "✅ Лучшее время для чтения утренних азкаров с Фаджра до восхода солнца.",
            storeLinks = "https://apps.apple.com/app/id6819638881",
        )

        assertEquals(
            """⚠️ Утренние азкары ⚠️
$separator
О рабы Аллаха, защитите себя и свою семью от сглаза, зависти и колдовства: прочитайте утренние азкары.
$separator

Абу ад-Дарда сказал:
إِنَّ الَّذِينَ أَلْسِنَتُهُمْ رَطْبَةٌ بِذِكْرِ اللَّهِ يَدْخُلُ الْجَنَّةَ وَهُوَ يَضْحَكُ
«Те, чьи языки влажные от поминания Аллаха, войдут в Рай смеясь».
Ахмад в «аз-Зухд», 726

$separator
✅ Лучшее время для чтения утренних азкаров с Фаджра до восхода солнца.

https://apps.apple.com/app/id6819638881""",
            text,
        )
        assertEquals(30, separator.length)
    }

    @Test
    fun `Без ссылок на приложение — текст заканчивается временем чтения`() {
        val text = azkarReminderText("Т", "П", "А", "П", "И", "Время", storeLinks = null)

        assertEquals(true, text.endsWith("$separator\nВремя"))
    }
}
