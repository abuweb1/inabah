import Foundation

/// Допуски экрана «Къибла» (решения 2026-10-24, обоснование — `docs/android/03-domain-logic.md` 3.10; Android `QiblaTuning`).
/// Компас телефона в обычных условиях ошибается на 5–15°, рядом с металлом — на десятки градусов,
/// поэтому значения не должны создавать ощущения точности выше этой. Время — в секундах.
nonisolated struct QiblaTuning: Hashable, Sendable {
    /// «Направление найдено» загорается, когда метка ближе к указателю…
    var alignEnterDegrees = 5.0
    /// …и гаснет, только когда отходит дальше: разрыв гасит дрожание датчика у границы.
    var alignExitDegrees = 8.0
    /// Постоянная времени сглаживания метки: дрожание датчика гасится, поворот не запаздывает.
    var smoothing: TimeInterval = 0.15
    /// Около противоположного направления сторона поворота держится прежней, пока метка не отойдёт от 180° дальше.
    var flipZoneDegrees = 10.0
    /// Пауза между показаниями, после которой метка встаёт сразу, без сглаживания (возврат на экран).
    var snapAfter: TimeInterval = 1
    /// Новый вход в совпадение даёт виброотклик, только если метка была вне совпадения хотя бы столько.
    var alignRearm: TimeInterval = 1
    /// Наклон экрана от горизонтали, после которого направление не подтверждается…
    var tiltMaxDegrees = 30.0
    /// …и меньше которого телефон снова «лежит ровно» (держат в руке около 30°).
    var tiltExitDegrees = 25.0
    /// Оценка точности датчика, хуже которой — «Компас неточен»…
    var headingAccuracyMaxDegrees = 20.0
    /// …и лучше которой компас снова точен.
    var headingAccuracyExitDegrees = 15.0
    /// Дальше — «Поверните направо», ближе — «Правее»…
    var turnFarDegrees = 45.0
    /// …ближе — «Немного правее» (набросок `qibla-v2.html`).
    var turnNearDegrees = 15.0
    /// Запас у этих границ: надпись не мигает от дрожания.
    var turnHysteresisDegrees = 2.0
    /// Сила поля отличается от ожидаемой в этой точке больше этой доли — металл или магнит рядом…
    var interferenceEnterRatio = 0.35
    /// …и снова чисто — меньше этой.
    var interferenceExitRatio = 0.25
    /// Ближе к Каабе «приблизительное» местоположение сдвигает направление на десятки градусов — нужно точное.
    var approximateNearKm = 50.0
    /// Координаты старше — «Местоположение устарело» с «Обновить»; направление не подтверждается.
    var locationStale: TimeInterval = 30 * 60
    /// Сколько ждать свежих координат, прежде чем показать ошибку.
    var locationTimeout: TimeInterval = 30

    static let `default` = QiblaTuning()

    /// iPhone: `CLHeading.headingAccuracy` - осторожная оценка, в помещении обычно 20-40° и при исправном
    /// компасе. С порогом Android (20°/15°; у датчика Xiaomi оценки нет вовсе) «Компас неточен» и приглушённая
    /// метка держались почти всё время (телефон пользователя, 2026-10-25). Сбитая калибровка
    /// (`headingAccuracy < 0`) по-прежнему - сразу «неточен» (`QiblaHeadingQuality`).
    static let iPhone: QiblaTuning = {
        var tuning = QiblaTuning()
        tuning.headingAccuracyMaxDegrees = 45
        tuning.headingAccuracyExitDegrees = 35
        return tuning
    }()
}
